export function electronConfigToLatex(config: string): string {
  return config
    .replace(/\[(\w+)\]/g, "\\textcolor{#6b7280}{[$1]}")
    .replace(/(\d[spdf])(\d+)/g, (_, orbital, count) => {
      const n = orbital[0];
      const l = orbital[1];
      const color =
        l === "s"
          ? "#ef4444"
          : l === "p"
            ? "#3b82f6"
            : l === "d"
              ? "#22c55e"
              : "#a855f7";
      return `\\textcolor{${color}}{${n}_{${l}}^{${count}}}`;
    })
    .replace(/\s+/g, "\\; ");
}

export function computeNuclearData(element: (typeof PeriodicData)[0]) {
  const Z = element.id;
  const A = Math.round(element.atomicMass);
  const N = A - Z;
  const isodiapher = N - Z;

  const isotones = PeriodicData.filter(
    (el) => Math.round(el.atomicMass) - el.id === N && el.id !== Z
  ).map((el) => `${el.symbol} (Z=${el.id})`);

  const isobars = PeriodicData.filter(
    (el) => Math.round(el.atomicMass) === A && el.id !== Z
  ).map((el) => `${el.symbol} (Z=${el.id})`);

  const isotopologues = element.isotopes.length > 1
    ? element.isotopes.map((iso) => {
      const massNum = parseInt(iso.replace(/[A-Za-z\-\+\[\]\(\)]/g, "")) || A;
      const neutronCount = massNum - Z;
      return `${element.symbol}-${neutronCount > 0 ? neutronCount : ""}${element.symbol} (${neutronCount}n difference)`;
    })
    : [];

  const isosteres = PeriodicData.filter(
    (el) => {
      const elA = Math.round(el.atomicMass);
      const elN = elA - el.id;
      return elN === N && el.id !== Z && Math.abs(el.electronegativity - element.electronegativity) < 0.5;
    }
  ).map((el) => `${el.symbol} (Z=${el.id}, EN=${el.electronegativity})`);

  return {
    neutrons: N,
    isodiapher,
    isotones,
    isobars,
    isotopologues,
    isosteres,
    allotropes: ALLOTROPES[Z] || [],
    mesomers: MESOMERS[Z] || [],
  };
}